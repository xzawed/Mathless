//! W7 binding generators: from the typed IR, emit a C header (`.h`) and a Delphi import
//! unit (`.pas`) for a compiled module (D14 artifacts).
//!
//! DRAFT status: these bindings encode the intended D18 ABI (`mlx_` prefix, reserved
//! `ml_module_abi_version`, 1-byte boolean), but the **C/Delphi host-load gate is BLOCKED**
//! (no `cl`/`gcc`/`dcc64`), so the bindings are not yet verified against a real host.

use std::fmt::Write as _;

use crate::ir::{IrFunction, IrModule, IrType};

fn c_type(t: IrType) -> &'static str {
    match t {
        IrType::F64 => "double",
        IrType::Bool => "bool",
    }
}

fn delphi_type(t: IrType) -> &'static str {
    match t {
        IrType::F64 => "Double",
        IrType::Bool => "Boolean",
    }
}

fn guard_name(dll_name: &str) -> String {
    let sanitized: String = dll_name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    format!("ML_{sanitized}_H")
}

/// Emit a C header exposing the module's exports. `dll_name` is the module name
/// (without extension), used for the include guard.
pub fn emit_c_header(module: &IrModule, dll_name: &str) -> String {
    let guard = guard_name(dll_name);
    let mut s = String::new();

    let _ = writeln!(
        s,
        "/* Generated by mlc — Mathless C ABI header for module '{dll_name}'. Do not edit."
    );
    let _ = writeln!(
        s,
        " * DRAFT: the C binding is NOT yet verified against a C host (D14 load gate BLOCKED)."
    );
    let _ = writeln!(
        s,
        " * `bool` is 1 byte to match the module's extern \"C\" ABI (D18). */"
    );
    let _ = writeln!(s, "#ifndef {guard}");
    let _ = writeln!(s, "#define {guard}");
    s.push('\n');
    let _ = writeln!(s, "#include <stdint.h>");
    let _ = writeln!(s, "#include <stdbool.h>");
    s.push('\n');
    let _ = writeln!(s, "#ifdef __cplusplus");
    let _ = writeln!(s, "extern \"C\" {{");
    let _ = writeln!(s, "#endif");
    s.push('\n');

    let _ = writeln!(s, "uint32_t ml_module_abi_version(void);");
    for f in &module.functions {
        let _ = writeln!(s, "{}", c_signature(f));
    }
    s.push('\n');

    let _ = writeln!(s, "#ifdef __cplusplus");
    let _ = writeln!(s, "}}");
    let _ = writeln!(s, "#endif");
    s.push('\n');
    let _ = writeln!(s, "#endif /* {guard} */");
    s
}

fn c_signature(f: &IrFunction) -> String {
    let params = if f.params.is_empty() {
        "void".to_string()
    } else {
        f.params
            .iter()
            .map(|p| format!("{} {}", c_type(p.ty), p.name))
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!("{} mlx_{}({});", c_type(f.ret), f.name, params)
}

/// Emit a Delphi import unit. `unit_name` is the Pascal unit name; `dll_name` the module
/// name (without extension) used in the `external` clause.
pub fn emit_delphi_unit(module: &IrModule, unit_name: &str, dll_name: &str) -> String {
    let mut s = String::new();

    let _ = writeln!(
        s,
        "{{ Generated by mlc — Mathless import unit for module '{dll_name}'. Do not edit."
    );
    let _ = writeln!(
        s,
        "  DRAFT: NOT yet verified against a Delphi host (D14 load gate BLOCKED)."
    );
    let _ = writeln!(
        s,
        "  Boolean is 1 byte to match the module ABI; do not use LongBool. }}"
    );
    let _ = writeln!(s, "unit {unit_name};");
    s.push('\n');
    let _ = writeln!(s, "interface");
    s.push('\n');
    let _ = writeln!(s, "const");
    let _ = writeln!(s, "  ML_MODULE = '{dll_name}.dll';");
    s.push('\n');
    let _ = writeln!(
        s,
        "function ml_module_abi_version: LongWord; cdecl; external ML_MODULE;"
    );
    for f in &module.functions {
        let _ = writeln!(s, "{} cdecl; external ML_MODULE;", delphi_signature(f));
    }
    s.push('\n');
    let _ = writeln!(s, "implementation");
    s.push('\n');
    let _ = writeln!(s, "end.");
    s
}

fn delphi_signature(f: &IrFunction) -> String {
    if f.params.is_empty() {
        format!("function mlx_{}: {};", f.name, delphi_type(f.ret))
    } else {
        let params = f
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, delphi_type(p.ty)))
            .collect::<Vec<_>>()
            .join("; ");
        format!(
            "function mlx_{}({}): {};",
            f.name,
            params,
            delphi_type(f.ret)
        )
    }
}
