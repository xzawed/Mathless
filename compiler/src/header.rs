//! W7 binding generators: from the typed IR, emit a C header (`.h`) and a Delphi import
//! unit (`.pas`) for a compiled module (D14 artifacts).
//!
//! Status: these bindings encode the D18 ABI (`mlx_` prefix, reserved
//! `ml_module_abi_version`, 1-byte boolean). The **C** binding is now verified end-to-end by
//! a real MSVC-built host (`hosts/c-host`, acceptance D) on every push. The **Delphi**
//! binding is verified too, but only where a Delphi is installed: `MATHLESS_GATE_DELPHI`
//! builds `hosts/delphi-host` with `dcc64` through the IDE and calls the modules. CI cannot
//! run that gate, so a change here is checked only by whoever runs it locally.

use std::fmt::Write as _;

use std::collections::HashMap;

use crate::ir::{IrArrayElem, IrFunction, IrModule, IrStmt, IrType};

fn c_type(t: IrType) -> &'static str {
    match t {
        // SPEC-string-input DP-S1: NUL-terminated, borrowed for the call.
        IrType::Str => "const char*",
        IrType::F64 => "double",
        IrType::Bool => "bool",
        IrType::I32 => "int32_t",
        // Borrowed and read-only, hence `const` — the same promise `const char*` makes for a
        // string. The LENGTH is a second parameter, written by `c_params` (SPEC-array-input
        // 2.2); this function names one type, not one parameter.
        IrType::Array(IrArrayElem::F64) => "const double*",
        IrType::Array(IrArrayElem::Bool) => "const bool*",
        IrType::Array(IrArrayElem::I32) => "const int32_t*",
    }
}

fn delphi_type(t: IrType) -> &'static str {
    match t {
        // NOT Delphi's `string`: that is a UTF-16 UnicodeString, and passing one here sends
        // the wrong bytes silently (SPEC-string-input section 5.2). The unit carries a
        // warning comment for the same reason.
        IrType::Str => "PAnsiChar",
        IrType::F64 => "Double",
        IrType::Bool => "Boolean",
        IrType::I32 => "Integer",
        // The pointer types Delphi already has for these. `PBoolean` is a pointer to a
        // ONE-BYTE Boolean, which is the size the module writes — the same hazard the unit's
        // header warns about for out-params, measured 2026-09-07.
        IrType::Array(IrArrayElem::F64) => "PDouble",
        IrType::Array(IrArrayElem::Bool) => "PBoolean",
        IrType::Array(IrArrayElem::I32) => "PInteger",
    }
}

/// The module name as it appears inside a macro name: uppercased, non-alphanumerics to `_`.
fn macro_stem(dll_name: &str) -> String {
    dll_name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn guard_name(dll_name: &str) -> String {
    format!("ML_{}_H", macro_stem(dll_name))
}

/// Name of the interface-fingerprint constant this header pins.
///
/// **Module-prefixed (DP-H10).** A fingerprint is per-module by definition, so an unprefixed
/// `ML_IFACE_HASH` would not merely collide — the second header would silently redefine the
/// first host's guard.
fn iface_hash_macro(dll_name: &str) -> String {
    format!("ML_{}_IFACE_HASH", macro_stem(dll_name))
}

/// Name of a module-defined error constant (Q14, closed 2026-09-03 → DP-Q1).
///
/// Same stem as the fingerprint above, so a header carries one naming rule rather than two.
/// It was two: `ML_ERR_<NAME>` had no prefix while `ML_<MODULE>_IFACE_HASH` had one — and the
/// fingerprint got its prefix *because* this debt was already written down (STATUS §5-5.4).
///
/// The collision it removes was measured, not imagined. `examples/refund.mls` and
/// `examples/shapes.mls` both declare `E_NEG`, with different values, exactly as two authors
/// who never met would. Unprefixed, including both headers in one translation unit produced
/// `C4005: macro redefinition` and `/WX` failed the build — acceptance D goes red without
/// this function.
///
/// No `#ifndef` guard, deliberately (DP-Q3): a guard would let the first header win and turn
/// the one loud failure into a silent wrong meaning. `ML_ST_*` may be guarded because it is
/// one agreed reserved code, not a per-module domain name.
fn error_macro(dll_name: &str, error_name: &str) -> String {
    format!("ML_{}_ERR_{}", macro_stem(dll_name), error_name)
}

/// Emit a C header exposing the module's exports. `dll_name` is the module name
/// (without extension), used for the include guard.
pub fn emit_c_header(module: &IrModule, dll_name: &str) -> String {
    let guard = guard_name(dll_name);
    let mut s = String::new();

    let _ = writeln!(
        s,
        "/* Generated by mlc - Mathless C ABI header for module '{dll_name}'. Do not edit."
    );
    let _ = writeln!(
        s,
        " * This GENERATOR is verified by acceptance D, both ways a C host can consume it:\n \
         * a C11 host built with MSVC cl on Windows x64 compiles this output and calls the\n \
         * module through LoadLibrary/GetProcAddress (hosts/c-host), and a second host links\n \
         * against the packaged <module>.lib and calls it with no run-time lookup at all\n \
         * (hosts/c-host-link). The output also compiles as C++ (cl /TP). That covers the\n \
         * generator, not this particular file.\n \
         * Not verified: any C or C++ compiler other than MSVC."
    );
    let _ = writeln!(
        s,
        " * `bool` is 1 byte to match the module's extern \"C\" ABI (D18). */"
    );
    let _ = writeln!(s, "#ifndef {guard}");
    let _ = writeln!(s, "#define {guard}");
    s.push('\n');
    let _ = writeln!(s, "#include <stdint.h>");
    let _ = writeln!(s, "#include <stdbool.h>");
    s.push('\n');
    // The interface fingerprint, next to the declarations it certifies. Putting the usage
    // in the header rather than only in HOST_ABI.md is deliberate: `runtime/ml_abi.h` is
    // this repo's own example of a contract nobody includes (STATUS §5-5.3).
    let _ = writeln!(
        s,
        "/* Interface fingerprint of THIS header. Compare it against the module's"
    );
    let _ = writeln!(
        s,
        " * ml_iface_hash() right after loading, and REFUSE the module when they differ:"
    );
    let _ = writeln!(
        s,
        " * export names are identical across incompatible interfaces, so resolution"
    );
    let _ = writeln!(
        s,
        " * succeeds and the call is then a wrong value or an access violation (measured)."
    );
    let _ = writeln!(s, " *");
    // NOTE: no nested comment markers here. A `/* ... */` inside this block would close it
    // at the FIRST `*/`, turning the remaining lines into code — MSVC C4138 and a broken
    // `/W4 /WX` build. A `contains()` assertion cannot see that; the header has to be
    // compiled, which is what acceptance D does.
    let _ = writeln!(
        s,
        " *   if (ml_iface_hash() != {}) {{",
        iface_hash_macro(dll_name)
    );
    let _ = writeln!(
        s,
        " *       return -1;      // built against a different interface: call nothing"
    );
    let _ = writeln!(s, " *   }}");
    let _ = writeln!(s, " *");
    let _ = writeln!(
        s,
        " * A change to a function BODY does not change this value; a change to a name,"
    );
    let _ = writeln!(
        s,
        " * type, parameter order, out-ness or error code does. */"
    );
    let _ = writeln!(
        s,
        "#define {} 0x{:016X}ULL",
        iface_hash_macro(dll_name),
        crate::iface::fingerprint(module)
    );
    s.push('\n');
    // DP-T6: the truncation status lives OUTSIDE the module's error namespace. That namespace
    // is per-module and now carries the module in its name (DP-Q1), so two modules cannot
    // collide there at all; this one is a runtime-wide band, identical in every module by
    // construction, so the `#ifndef` makes two generated headers in one translation unit
    // benign rather than a redefinition error. The two rules are opposite on purpose — see
    // `error_macro` for why guarding a per-module name would be a trap.
    if module
        .functions
        .iter()
        .any(|f| f.exported && f.ret == IrType::Str)
    {
        let _ = writeln!(
            s,
            "/* Q12 caller-allocates protocol: a buffer too small to hold the"
        );
        let _ = writeln!(
            s,
            " * result, NUL included. Truncation is a FAILURE, not a short"
        );
        let _ = writeln!(
            s,
            " * success - nothing is written, and *ml_needed is the exact size"
        );
        let _ = writeln!(s, " * to allocate, in the same unit as ml_cap. */");
        let _ = writeln!(s, "#ifndef ML_ST_INSUFFICIENT_BUFFER");
        let _ = writeln!(s, "#define ML_ST_INSUFFICIENT_BUFFER (-1)");
        let _ = writeln!(s, "#endif");
        s.push('\n');
    }

    // The other reserved negative (SPEC-array-input DP-A7), on the same terms as the one
    // above: a runtime-wide band OUTSIDE the module's error namespace, `#ifndef`-guarded so
    // two generated headers in one translation unit are benign, and emitted only for a module
    // that can actually return it — one that indexes an array.
    //
    // A host that had to retype `-2` is a host holding a number the header never promised.
    if module
        .functions
        .iter()
        .any(|f| crate::ir::first_index(&f.body).is_some())
    {
        let _ = writeln!(
            s,
            "/* An array index outside 0..len. The out-parameter is NOT written"
        );
        let _ = writeln!(
            s,
            " * (D17), and the length is the one YOU passed alongside the pointer. */"
        );
        let _ = writeln!(s, "#ifndef ML_ST_INDEX_OUT_OF_RANGE");
        let _ = writeln!(
            s,
            "#define ML_ST_INDEX_OUT_OF_RANGE ({})",
            crate::abi::ML_ST_INDEX_OUT_OF_RANGE
        );
        let _ = writeln!(s, "#endif");
    }
    // D17 error codes (module-defined, positive i32). Constants — not exported symbols.
    if !module.errors.is_empty() {
        for e in &module.errors {
            let _ = writeln!(s, "#define {} {}", error_macro(dll_name, &e.name), e.code);
        }
        s.push('\n');
    }
    let _ = writeln!(s, "#ifdef __cplusplus");
    let _ = writeln!(s, "extern \"C\" {{");
    let _ = writeln!(s, "#endif");
    s.push('\n');

    let _ = writeln!(s, "uint32_t ml_module_abi_version(void);");
    let _ = writeln!(s, "uint64_t ml_iface_hash(void);");
    let provenance = error_provenance(module);
    // Bindings describe the module's SURFACE: internal functions are not callable by a host
    // and must not appear here (SPEC-calls section 2.3).
    for f in module.functions.iter().filter(|f| f.exported) {
        // DP-F10: which codes can actually reach the host through THIS function. Comments
        // only — the declaration below is byte-identical to what it was before.
        if f.fallible {
            if let Some(codes) = provenance.get(f.name.as_str()) {
                let list = if codes.is_empty() {
                    "(no domain error)".to_string()
                } else {
                    codes
                        .iter()
                        .map(|c| error_macro(dll_name, c))
                        .collect::<Vec<_>>()
                        .join(", ")
                };
                let _ = writeln!(s, "/* may fail with: {list} */");
            }
        }
        let _ = writeln!(s, "{}", c_signature(f));
    }
    s.push('\n');

    let _ = writeln!(s, "#ifdef __cplusplus");
    let _ = writeln!(s, "}}");
    let _ = writeln!(s, "#endif");
    s.push('\n');
    let _ = writeln!(s, "#endif /* {guard} */");
    s
}

/// For every function, the error NAMES it can fail with — its own `fail`s plus everything
/// reachable through `try` (DP-F10).
///
/// Only `try` edges carry errors: a plain call cannot target a fallible callee, so an
/// infallible helper can never contribute a code. `reject_recursion` has already proved the
/// call graph acyclic, so the walk terminates without a visited-set for cycles — but one is
/// kept anyway, because this function must not hang if it is ever reached with hand-built IR.
///
/// Names, not numbers: the header prints `ML_<MODULE>_ERR_<NAME>`, which is what a host reads.
fn error_provenance(module: &IrModule) -> HashMap<&str, Vec<String>> {
    let code_name: HashMap<i32, &str> = module
        .errors
        .iter()
        .map(|e| (e.code, e.name.as_str()))
        .collect();

    /// Direct `fail` codes and `try` callees of one body.
    fn scan<'a>(body: &'a [IrStmt], codes: &mut Vec<i32>, callees: &mut Vec<&'a str>) {
        for s in body {
            match s {
                IrStmt::Fail(c) => codes.push(*c),
                IrStmt::TryCall { callee, .. } => callees.push(callee.as_str()),
                IrStmt::If { body, .. } | IrStmt::While { body, .. } => scan(body, codes, callees),
                IrStmt::Return(_)
                | IrStmt::Let { .. }
                | IrStmt::Assign { .. }
                | IrStmt::AssignOut { .. } => {}
            }
        }
    }

    let mut direct: HashMap<&str, (Vec<i32>, Vec<&str>)> = HashMap::new();
    for f in &module.functions {
        let (mut codes, mut callees) = (Vec::new(), Vec::new());
        scan(&f.body, &mut codes, &mut callees);
        direct.insert(f.name.as_str(), (codes, callees));
    }

    fn reach<'a>(
        name: &'a str,
        direct: &HashMap<&'a str, (Vec<i32>, Vec<&'a str>)>,
        seen: &mut Vec<&'a str>,
        out: &mut Vec<i32>,
    ) {
        if seen.contains(&name) {
            return;
        }
        seen.push(name);
        let Some((codes, callees)) = direct.get(name) else {
            return;
        };
        for c in codes {
            if !out.contains(c) {
                out.push(*c);
            }
        }
        for callee in callees {
            reach(callee, direct, seen, out);
        }
    }

    let mut result = HashMap::new();
    for f in &module.functions {
        let mut codes = Vec::new();
        let mut seen = Vec::new();
        reach(f.name.as_str(), &direct, &mut seen, &mut codes);
        codes.sort_unstable();
        result.insert(
            f.name.as_str(),
            codes
                .iter()
                .filter_map(|c| code_name.get(c).map(|n| (*n).to_string()))
                .collect(),
        );
    }
    result
}

/// A user-chosen parameter name, placed where the preprocessor cannot reach it.
///
/// **A name this project does not control must not be a token in a header.** Three name rules
/// have now been written for one reader and met another: the C keyword list missed C++
/// keywords (#159), the keyword lists missed `<stdint.h>`'s macros (#159), and the header
/// compiled alone missed the platform headers a host includes *before* it. Measured, with
/// `mlc build` reporting exit 0 every time, `hosts/c-host/host.c`'s own include order
/// (`<windows.h>` first) and `cl /W4 /WX /std:c11`:
///
/// ```text
/// double mlx_f(double TRUE);      -> double mlx_f(double 1);          C2059, C2143
/// double mlx_f(double VOID);      -> double mlx_f(double void);       C2632
/// double mlx_f(double small);     -> double mlx_f(double char);       C2632
/// double mlx_f(double WINAPI);    -> double mlx_f(double __stdcall);  C2220
/// ```
///
/// A fourth list cannot close this: the macros defined by headers a host includes are an
/// unbounded set this project does not own. A **comment** can, and by construction rather
/// than by maintenance — comments are removed in translation phase 3, before macro expansion
/// in phase 4, so no macro and no keyword can touch one. Measured: all seven names above, and
/// `new`/`template`/`INT32_MAX`, compile clean in this form as C **and** as C++.
///
/// The C ABI loses nothing: a parameter name in a prototype has never affected linkage. What
/// it costs is a third-party binding generator reading our header, which would see unnamed
/// parameters — this project ships its own bindings from the IR (`.pas` today, and those keep
/// real names: Pascal has no preprocessor), so the loss is to tools we do not use.
///
/// **Only user-chosen names move.** `ml_buf`, `ml_cap`, `ml_needed` and `out_value` stay as
/// real tokens: they are the compiler's own namespace, already reserved from user identifiers,
/// documented by name in this very header, and no header outside this project defines them.
/// The rule is not "hide every name" — it is "a name we do not control does not go where a
/// preprocessor can eat it".
fn c_param_name(name: &str) -> String {
    format!("/* {name} */")
}

fn c_signature(f: &IrFunction) -> String {
    let mut parts: Vec<String> = Vec::with_capacity(f.params.len());
    for p in &f.params {
        // A declared `out` is a pointer, exactly like D17's `out_value` below it.
        if p.out {
            parts.push(format!("{}* {}", c_type(p.ty), c_param_name(&p.name)));
        } else {
            parts.push(format!("{} {}", c_type(p.ty), c_param_name(&p.name)));
        }
        // An array brings its length with it, immediately after the pointer and before
        // whatever the author declared next (SPEC-array-input DP-A2). The unit is ELEMENTS,
        // which is not the unit `ml_cap`/`ml_needed` use — those are bytes.
        if matches!(p.ty, IrType::Array(_)) {
            parts.push(format!(
                "int32_t {}",
                c_param_name(&format!("{}_len", p.name))
            ));
        }
    }
    if f.ret == IrType::Str {
        // SPEC-string-return DP-T1/T4: the Q12 triple IS the return value, so it comes last
        // (DP-O1 unchanged). `ml_cap` and `*ml_needed` are total bytes INCLUDING the NUL, on
        // every path — so the host's retry is exactly `ml_cap = *ml_needed`.
        parts.push("char* ml_buf".to_string());
        parts.push("int32_t ml_cap".to_string());
        parts.push("int32_t* ml_needed".to_string());
        format!("int32_t mlx_{}({});", f.name, join_c_params(parts))
    } else if f.fallible {
        // D17: i32 status return + a `T*` out-param.
        parts.push(format!("{}* out_value", c_type(f.ret)));
        format!("int32_t mlx_{}({});", f.name, join_c_params(parts))
    } else {
        format!(
            "{} mlx_{}({});",
            c_type(f.ret),
            f.name,
            join_c_params(parts)
        )
    }
}

fn join_c_params(parts: Vec<String>) -> String {
    if parts.is_empty() {
        "void".to_string()
    } else {
        parts.join(", ")
    }
}

/// Emit a Delphi import unit. `dll_name` is the module name without extension: it names the
/// unit, names the file `mlc build` writes it to, and appears in every `external` clause.
///
/// **It used to take a separate `unit_name`, and nothing in production ever passed a
/// different value.** Object Pascal requires the unit name to match the file name, so a
/// second name could only ever be wrong -- and it was: four tests passed `Mlx_<name>`,
/// including the golden that freezes the whole `.pas` corpus. The repository's only
/// regression signal for those 535 lines was pinning a unit name `mlc build` has never
/// written. Deleting the parameter is what makes that impossible rather than merely
/// checked.
pub fn emit_delphi_unit(module: &IrModule, dll_name: &str) -> String {
    let mut s = String::new();

    let _ = writeln!(
        s,
        "{{ Generated by mlc - Mathless import unit for module '{dll_name}'. Do not edit."
    );
    // What this line may claim has now changed TWICE, and each time the old wording shipped
    // to users for a while before anyone noticed:
    //   2026-09-07 (9-15): a Delphi host compiled these units by hand, so "never verified"
    //                      became false. The replacement said "BY HAND AND NOT GATED".
    //   2026-09-09 (9-20): the gate learned to fall back to `bds.exe -b` when dcc64 refuses
    //                      command-line builds, so it RUNS -- and "nothing repeats it"
    //                      became false in turn. That is what this wording fixes.
    // The durable facts are which gate checks this generator and where that gate does not
    // run, so those are what the text states; it credits the GENERATOR rather than this
    // file, exactly as the C header does.
    let _ = writeln!(
        s,
        "  This GENERATOR is checked against a real Delphi host by MATHLESS_GATE_DELPHI,\n  \
         which builds hosts/delphi-host with dcc64 - through the IDE (bds.exe -b), since\n  \
         the edition to hand refuses command-line builds - and calls the modules over the\n  \
         C ABI. That gate runs on a developer machine, not in CI: the runner has neither\n  \
         Delphi nor an interactive session. So a change to this generator is verified only\n  \
         if whoever makes it runs that gate; CI will not catch it."
    );
    let _ = writeln!(
        s,
        "  Boolean is 1 byte to match the module ABI; do not use LongBool."
    );
    // Only when the module takes an array, for the same reason the string note is conditional.
    //
    // MEASURED 2026-09-10 in hosts/delphi-host/host.dpr, which does both of these on purpose.
    if module
        .functions
        .iter()
        .any(|f| f.exported && f.params.iter().any(|p| matches!(p.ty, IrType::Array(_))))
    {
        let _ = writeln!(
            s,
            "\n  An array parameter is TWO parameters here: the pointer, then the length\n  \
             in ELEMENTS -- not bytes; ml_cap and ml_needed are bytes and these are not. The\n  \
             module borrows the memory for the call, never writes to it, never keeps it.\n  \
             The length must be TRUE: the bounds check tests the number YOU pass, so a\n  \
             length larger than the array reads past its end. That is undefined and the\n  \
             module cannot catch it - the same kind of contract as a NUL-terminated\n  \
             string.\n  \
             - Pass a dynamic array as `@Arr[0], Length(Arr)`.\n  \
             - EMPTY arrays: `@Arr[0]` has no element 0. With range checking off (the\n    \
             release default) it does not raise - it yields the array's own nil pointer,\n    \
             which is what a length of 0 wants, because the module never dereferences.\n    \
             Under the $R+ directive the same line RAISES. So write it as:\n      \
             if Length(Arr) = 0 then P := nil else P := @Arr[0];\n  \
             - An index outside 0..len-1 returns ML_ST_INDEX_OUT_OF_RANGE and writes no\n    \
             out-parameter."
        );
    }
    // Only when the module actually takes a string — an unrelated module should not carry a
    // warning about a type it never mentions.
    if module
        .functions
        .iter()
        .any(|f| f.exported && f.params.iter().any(|p| p.ty == IrType::Str))
    {
        // Spells out which cast does what, because the blanket "a UnicodeString silently
        // matches nothing" turned out to be wrong in BOTH directions. MEASURED 2026-09-10 on
        // Delphi CE 37.0 Win64, through this ABI, by hosts/delphi-host/host.dpr -- which now
        // writes all three spellings on purpose and pins each one.
        let _ = writeln!(
            s,
            "\n  PAnsiChar is NOT Delphi's `string`, which is UTF-16 (UnicodeString). The module\n  \
             compares BYTES up to the NUL and never inspects the encoding (SPEC-string-input\n  \
             DP-S2), so how you build the argument decides whether it can match at all.\n  \
             MEASURED on Delphi 37.0 Win64 through this ABI, sending \"UPSN\":\n  \
             - PAnsiChar(AnsiString(S)) - CORRECT. Sends 55 50 53 4E 00. Inline as an\n    \
             argument is fine (measured): the temporary a cast expression makes lives to\n    \
             the end of the STATEMENT, and the call is that statement. What you must not\n    \
             do is KEEP the pointer - `P := PAnsiChar(AnsiString(S))` and use P in a later\n    \
             statement reads a dead temporary. That failure is undefined behaviour, so it\n    \
             is stated as a rule and not claimed as measured.\n  \
             - PAnsiChar(S) on a UnicodeString - WRONG. It does NOT convert. It sends the\n    \
             UTF-16 bytes 55 00 50 00 53 00 4E 00, identical to the Pointer spelling below,\n    \
             so the module reads to the first NUL and sees ONE character. The compiler does\n    \
             object - W1044 Suspicious typecast of string to PAnsiChar - so it is wrong but\n    \
             not silent.\n  \
             - PAnsiChar(Pointer(S)) - WRONG and SILENT. The same UTF-16 bytes, and dcc64\n    \
             says nothing about it at all. Nothing crashes.\n  \
             Plain `string` IS UnicodeString in Delphi, so PAnsiChar(S) on one is the SECOND\n  \
             line, not the first. Free Pascal in -Mdelphi mode does not emulate that - its\n  \
             `string` is AnsiString, so identical source is correct there and wrong here.\n  \
             Measured both ways, which is why an FPC run cannot stand in for a Delphi one.\n  \
             With an EXPLICIT UnicodeString, Free Pascal sends the same bytes as Delphi\n  \
             (measured), so the trap itself is not Embarcadero-only - what differs is what\n  \
             `string` means."
        );
    }
    let _ = writeln!(s, "  }}");
    let _ = writeln!(s, "unit {dll_name};");
    s.push('\n');
    let _ = writeln!(s, "interface");
    s.push('\n');
    let _ = writeln!(s, "const");
    let _ = writeln!(s, "  ML_MODULE = '{dll_name}.dll';");
    // Interface fingerprint of this unit — compare against ml_iface_hash after loading and
    // refuse the module when they differ (see the C header for the full note).
    //
    // The `UInt64(...)` cast is not decoration. A bare `$8120E9C099B13F94` is typed as a
    // SIGNED Int64 first, so every fingerprint with the top bit set — measured: 11 of the 19
    // example modules — makes Free Pascal 3.2.2 (`-Mdelphi`) warn "range check error while
    // evaluating constants". The value it stores is still right (measured: all three
    // spellings print 9304693843568967572); what breaks is a consumer building with
    // warnings-as-errors, which is the standard this repo holds its own C header to.
    let _ = writeln!(
        s,
        "  {}: UInt64 = UInt64(${:016X});",
        iface_hash_macro(dll_name),
        crate::iface::fingerprint(module)
    );
    // D17 error codes (module-defined, positive i32).
    for e in &module.errors {
        let _ = writeln!(s, "  {} = {};", error_macro(dll_name, &e.name), e.code);
    }
    // The Q12 truncation status, on the same terms the C header gives it (DP-T6): a
    // runtime-wide band, OUTSIDE the module's error namespace, and emitted only for a module
    // that can actually return it.
    //
    // The header defined and explained it from the start and the unit said nothing, so a
    // Delphi host had to retype `-1` — the very thing `hosts/c-host/host.c` refuses to do on
    // the C side ("the error constant comes from the header too … not from a number retyped
    // here"). No `#ifndef` equivalent is needed or possible: a Pascal unit has its own
    // namespace, so two generated units in one program do not collide the way two included
    // headers would.
    if module
        .functions
        .iter()
        .any(|f| f.exported && f.ret == IrType::Str)
    {
        let _ = writeln!(
            s,
            "  {{ Q12 caller-allocates protocol: the buffer was too small to hold the result,\n    \
             NUL included. Truncation is a FAILURE, not a short success - nothing is written,\n    \
             and ml_needed is the exact size to allocate, in the same unit as ml_cap. }}"
        );
        let _ = writeln!(s, "  ML_ST_INSUFFICIENT_BUFFER = -1;");
    }
    if module
        .functions
        .iter()
        .any(|f| crate::ir::first_index(&f.body).is_some())
    {
        let _ = writeln!(
            s,
            "  {{ An array index outside 0..len. The out-parameter is NOT written (D17), and\n    \
             the length is the one YOU passed alongside the pointer. }}"
        );
        let _ = writeln!(
            s,
            "  ML_ST_INDEX_OUT_OF_RANGE = {};",
            crate::abi::ML_ST_INDEX_OUT_OF_RANGE
        );
    }
    s.push('\n');
    let _ = writeln!(
        s,
        "function ml_module_abi_version: LongWord; cdecl; external ML_MODULE;"
    );
    let _ = writeln!(
        s,
        "function ml_iface_hash: UInt64; cdecl; external ML_MODULE;"
    );
    for f in module.functions.iter().filter(|f| f.exported) {
        let _ = writeln!(s, "{} cdecl; external ML_MODULE;", delphi_signature(f));
    }
    s.push('\n');
    let _ = writeln!(s, "implementation");
    s.push('\n');
    let _ = writeln!(s, "end.");
    s
}

fn delphi_signature(f: &IrFunction) -> String {
    let mut parts: Vec<String> = Vec::with_capacity(f.params.len());
    for p in &f.params {
        // Delphi already spells this for `out_value`; a declared out gets the same keyword.
        if p.out {
            parts.push(format!("out {}: {}", p.name, delphi_type(p.ty)));
        } else {
            parts.push(format!("{}: {}", p.name, delphi_type(p.ty)));
        }
        if matches!(p.ty, IrType::Array(_)) {
            parts.push(format!("{}_len: Integer", p.name));
        }
    }
    if f.ret == IrType::Str {
        // DP-T3: `PByte`, deliberately NOT `PAnsiChar`. Both silent Delphi misspellings that
        // the string-INPUT slice could only warn about — `PAnsiChar(S)` on a UnicodeString and
        // `PAnsiChar(Pointer(S))` — become COMPILE ERRORS against a `PByte` parameter. Loud
        // beats documented.
        //
        // `ml_buf` is a VALUE parameter, never `out ml_buf: PByte`: that spelling passes a
        // `PByte*`, and the module would write the answer's first bytes over the host's
        // pointer variable instead of into the buffer.
        parts.push("ml_buf: PByte".to_string());
        parts.push("ml_cap: Integer".to_string());
        parts.push("out ml_needed: Integer".to_string());
        format!("function mlx_{}({}): Integer;", f.name, parts.join("; "))
    } else if f.fallible {
        // D17: Integer status return + an `out` param (Delphi `out` == C `T*` for f64/bool).
        parts.push(format!("out out_value: {}", delphi_type(f.ret)));
        format!("function mlx_{}({}): Integer;", f.name, parts.join("; "))
    } else if parts.is_empty() {
        format!("function mlx_{}: {};", f.name, delphi_type(f.ret))
    } else {
        format!(
            "function mlx_{}({}): {};",
            f.name,
            parts.join("; "),
            delphi_type(f.ret)
        )
    }
}
